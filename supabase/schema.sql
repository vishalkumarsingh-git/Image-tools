-- Run this once in Supabase Dashboard → SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  selected_model text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.edit_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  filename text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.edit_history enable row level security;

drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
  on public.profiles for select to authenticated
  using (auth.uid() = id);

drop policy if exists "Users can insert own profile" on public.profiles;
create policy "Users can insert own profile"
  on public.profiles for insert to authenticated
  with check (auth.uid() = id);

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users can read own edit history" on public.edit_history;
create policy "Users can read own edit history"
  on public.edit_history for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can add own edit history" on public.edit_history;
create policy "Users can add own edit history"
  on public.edit_history for insert to authenticated
  with check (auth.uid() = user_id);

